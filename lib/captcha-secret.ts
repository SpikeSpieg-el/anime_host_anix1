/**
 * Единый источник секрета captcha.
 *
 * Модуль ТОЛЬКО для сервера (route handlers): он читает `process.env` и
 * импортирует `node:crypto`, поэтому в клиентский бандл попадать не должен.
 *
 * Зачем он нужен
 * --------------
 * Раньше секрет объявлялся в четырёх местах с литеральным дефолтом вида
 * `process.env.CAPTCHA_SECRET || "<строка в репозитории>"`, причём в одном
 * из файлов строка была другой.
 *
 * Это две проблемы, и обе были проверены на боевом домене.
 *
 * 1) Дефолт лежит в публичном git. Поскольку ключ выводится из секрета
 *    (`sha256("captcha-puzzle:v2:" + secret)`), знание секрета означает
 *    возможность самому запечатать корректный payload. Именно это и было
 *    сделано при аудите: токен, выданный https://weeb-x.com, расшифровался
 *    публичным дефолтом и отдал верные координаты — то есть капча на боевом
 *    домне не защищала ничего.
 *
 * 2) Дефолты РАЗНЫЕ в разных файлах. При незаданной переменной токен,
 *    выданный одним эндпоинтом, не проходил проверку в другом. Тихая
 *    поломка, которую замечаешь только в проде.
 *
 * Поэтому дефолтов здесь нет вообще. Переменная обязана быть задана, и её
 * отсутствие должно падать громко и с понятным текстом, а не молча
 * подставлять секрет из репозитория.
 */

/** Минимальная длина секрета. 32 hex-символа — стандартный размер AES-256-ключа. */
const MIN_SECRET_LENGTH = 32

/**
 * Секрет captcha.
 *
 * Бросает исключение, если переменная не задана или слишком короткая.
 * Проверка ленивая (в момент вызова, а не на импорте): иначе сборка падала бы
 * там, где секрет вообще не нужен, — например при билде статических страниц.
 */
export function getCaptchaSecret(): string {
  const secret = process.env.CAPTCHA_SECRET?.trim()

  if (!secret) {
    throw new Error(
      "CAPTCHA_SECRET не задан. Без него капча не защищает ничего, поэтому " +
        "дефолта больше нет намеренно. Сгенерируйте секрет командой " +
        "`npm run captcha:secret` и пропишите его в окружении " +
        "(Coolify -> Service -> Environment variables), затем перезапустите сервис.",
    )
  }

  if (secret.length < MIN_SECRET_LENGTH) {
    throw new Error(
      `CAPTCHA_SECRET слишком короткий: ${secret.length} симв., минимум ${MIN_SECRET_LENGTH}. ` +
        "Сгенерируйте новый командой `npm run captcha:secret`.",
    )
  }

  return secret
}

