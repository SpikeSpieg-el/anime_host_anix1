/**
 * Сырой рейтинг Shikimori → понятная возрастная метка.
 *
 * Код Shikimori («R», «R+PLUS», «PG_13») зритель прочесть не может: на
 * сайте под ним подразумеваются стандартные возрастные границы 0+/6+/
 * 12+/16+/18+. Прежде чем это появилось, на странице /watch висела пилюля
 * «Возрастной рейтинг: R+PLUS» — длинная, ломала строку мета-пилюль и
 * требовала знания системы Shikimori.
 *
 * Два места использования:
 *  - бейдж поверх обложки (лейбл + цвет по возрасту);
 *  - предупреждение NSFW над плеером (полное описание словами).
 *
 * Известная сетка Shikimori:
 *   g      → 0+  (все возрасты)
 *   pg     → 6+  (детям, присутствие родителей)
 *   pg_13  → 12+ (подростки)
 *   r      → 16+ (насилие, грубый язык)
 *   r_plus → 18+ (этти, лёгкая эротика)
 *   rx     → 18+ (хентай)
 */
export interface AgeRatingInfo {
  /** Короткий лейбл для бейджа: «16+», «18+ Этти». */
  label: string
  /** Полное описание словами: «только для взрослых: …». */
  description: string
  /** Tailwind-классы бейджа: цвет по возрастной границе. */
  badgeClass: string
  /**
   * Развёрнутое пояснение для диалога по клику на бейдж: что именно
   * стоит за меткой и почему маленьким смотреть нельзя.
   */
  explain: string
}

