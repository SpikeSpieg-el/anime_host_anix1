/** Вся известная сетка — для легенды «что означают метки» в диалоге. */
export const AGE_RATING_LIST: AgeRatingInfo[] = Object.values(AGE_RATING_MAP)

/**
 * Возрастная метка по строковому рейтингу Shikimori.
 * Неизвестный код → null: пусто лучше, чем выдуманное значение.
 */
export function getAgeRatingInfo(rating: string | null | undefined): AgeRatingInfo | null {
  const key = (rating ?? "").trim().toLowerCase()
  if (!key) return null
  return AGE_RATING_MAP[key] ?? null
}
