/**
 * Санитайзер ссылок в тексте мнения редакции.
 *
 * ЗАЧЕМ ВЫДЕЛЕНО В ОТДЕЛЬНЫЙ МОДУЛЬ
 *   Мнения редакции рендерятся на ПУБЛИЧНОЙ странице тайтла для всех
 *   гостей сайта, поэтому href из контента нельзя отдавать как есть.
 *   Раньше parseInlineMarkdown подставлял `[текст](url)` в <a href> без
 *   какой-либо проверки, и `[клик](javascript:alert(document.cookie))`
 *   становился рабочей ссылкой — stored XSS, доступный всему трафику.
 *
 *   Функция экспортируется, чтобы её можно было покрыть тестами: правила
 *   безопасности обязаны проверяться автоматически, иначе их очень легко
 *   «случайно» смягчить правкой соседнего кода.
 */

/** Схемы, которые разрешено отдавать в href. */
const SAFE_LINK_SCHEMES = new Set(["http:", "https:"])

/** Код C0-пробела (пробелы тоже) и DEL. */
const CONTROL_CHAR_MAX = 0x20
const DEL = 0x7f

/**
 * Возвращает безопасный href или null.
 *
 * null означает «не показывать ссылку вообще» — вызывающий код рендерит
 * обычный текст без возможности клика.
 */
export function sanitizeEditorialLink(rawUrl: string): string | null {
  // Пробелы и управляющие символы внутри URL — всегда признак попытки
  // спрятать схему: браузер тримает их сам, поэтому `java<TAB>script:`
  // проскочило бы мимо сравнения строк, если бы мы сравнивали сырое
  // значение. Перебираем по codePoint, а не регуляркой: литералы с
  // управляющими символами внутри исходника неудобно читать и легко
  // испортить при копировании.
  for (const character of rawUrl) {
    const code = character.codePointAt(0) as number
    if (code <= CONTROL_CHAR_MAX || code === DEL) return null
  }

  try {
    const url = new URL(rawUrl)
    if (!SAFE_LINK_SCHEMES.has(url.protocol)) return null
    return url.href
  } catch {
    // Относительные ссылки без схемы new URL() не разбирает. Они безопасны:
    // у них не может быть другой протокол. Но «//evil.com» и «/\evil.com» —
    // схема-относительные URL, которые уводят на чужой домен, поэтому
    // оставляем только одиночный слеш.
    if (rawUrl.startsWith("/") && !rawUrl.startsWith("//") && !rawUrl.startsWith("/\\")) {
      return rawUrl
    }
    return null
  }
}