/**
 * Устоявшиеся латинские написания, которые НЕ совпадают с механической
 * транслитерацией.
 *
 * Транслитерация даёт «Исекай» → «isekay» (по правилу й → y) и «Сёнэн» →
 * «senen». В фанатской среде эти слова пишут иначе: Isekai, Shonen, Seinen,
 * Shojo, Josei — именно в таком виде они встречаются в чужих ссылках,
 * сохранённых закладках и в выдаче конкурентов (/isekai, /isekai-y18/).
 *
 * Менять адреса после индексации дорого, поэтому фиксируем их здесь, до
 * первого входа в индекс. Всё, чего здесь нет, транслитерируется механически.
 */
