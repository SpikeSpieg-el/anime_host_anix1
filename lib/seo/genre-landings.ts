/**
 * Список лендингов, один на каждый жанр из GENRES_MAP.
 *
 * Порядок стабильный (порядок ключей в объекте), чтобы sitemap и
 * generateStaticParams не «прыгали» между сборками.
 */
export const GENRE_LANDINGS: GenreLanding[] = Object.entries(GENRES_MAP).map(
  ([name, genreId], index) => ({
    slug: GENRE_SLUG_OVERRIDES[name] ?? slugifyAnimeTitle(name),
    name,
    genreId,
    hint: GENRE_HINTS[name] ?? name.toLowerCase(),
    accent: ACCENTS[index % ACCENTS.length],
    indexable: !NOINDEX_GENRE_IDS.has(genreId),
  }),
)

/** Жанры, которые можно отдавать поисковикам и показывать в хабе /genre. */
export const INDEXABLE_GENRE_LANDINGS: GenreLanding[] = GENRE_LANDINGS.filter(
  (genre) => genre.indexable,
)

const BY_SLUG = new Map(GENRE_LANDINGS.map((genre) => [genre.slug, genre]))

/**
 * Рукописные синонимы адресов → канонический slug.
 *
 * Это НЕ структурированные данные, а то, как люди и другие сайты пишут жанр
 * в URL: anime-portal.su и anime1.best держат выдачу на /isjekaj/, а не на
 * /isekai. Без 301 с таких адресов мы отвечаем 404 и теряем ссылки, которые
 * на нас уже кто-то поставил.
 */
const EXTRA_GENRE_ALIASES: Record<string, string[]> = {
  isekai: ["isjekaj", "iseke", "isekey", "isecai"],
  romantika: ["romance", "romantiki"],
  komediya: ["comedy"],
  fentezi: ["fantasy"],
  ekshen: ["action"],
  priklyucheniya: ["adventure"],
  uzhasy: ["horror"],
  detektiv: ["mystery", "detective"],
  fantastika: ["sci-fi", "scifi"],
  sport: ["sports"],
}

/**
 * Полная карта «короткий адрес → канонический slug жанра».
 *
 * Собирается автоматически из трёх источников:
 *   1. сам slug жанра: /isekai → /genre/isekai;
 *   2. механическая транслитерация, если она отличается: /isekay, /seynen —
 *      именно так получается, когда русское название переписывают вручную;
 *   3. рукописные синонимы из EXTRA_GENRE_ALIASES.
 *
 * Только индексируемые жанры: 18+ адреса намеренно не отдаём даже через 301,
 * чтобы ссылка на /хентай не указывала на страницу с noindex.
 */
export const GENRE_PATH_ALIASES: Record<string, string> = (() => {
  const aliases: Record<string, string> = {}

  for (const genre of INDEXABLE_GENRE_LANDINGS) {
    aliases[genre.slug] = genre.slug

    const transliterated = slugifyAnimeTitle(genre.name)
    if (transliterated && transliterated !== genre.slug) {
      aliases[transliterated] = genre.slug
    }

    for (const extra of EXTRA_GENRE_ALIASES[genre.slug] ?? []) {
      aliases[extra] = genre.slug
    }
  }

  return aliases
})()

/**
 * Куда отдать 301 для «короткого» адреса вида /isekai.
 *
 * Принимает pathname (со слешем или без, с хвостовым / или без) и отдаёт
 * /genre/<slug> либо null. Сопоставление строгое, по таблице: никакого разбора
 * «похожих» строк, иначе любой односегментный путь рисковал бы стать
 * редиректом.
 */
export function resolveGenreAlias(pathname: string): string | null {
  const segment = pathname.replace(/^\/+|\/+$/g, "").toLowerCase()
  if (!segment || segment.includes("/")) return null

  const slug = GENRE_PATH_ALIASES[segment]
  return slug ? getGenrePath(slug) : null
}

/** Лендинг по slug'у или undefined, если такого жанра нет. */
export function getGenreLanding(slug: string | undefined): GenreLanding | undefined {
  if (!slug) return undefined
  return BY_SLUG.get(slug.toLowerCase())
}

/** Канонический путь лендинга. */
export function getGenrePath(slug: string): string {
  return `/genre/${slug}`
}

/**
 * Title по образцу страниц /watch: сам запрос («смотреть исекай») должен
 * дословно встречаться в строке, а бренд — в конце.
 */
export function buildGenreTitle(genre: GenreLanding): string {
  return `Смотреть ${genre.name} аниме онлайн бесплатно в HD — Weebx`
}

/**
 * Description. `count` — сколько тайтлов реально отдала выборка: конкретное
 * число («386 аниме») работает заметно лучше, чем расплывчатое «много аниме».
 * Если выборка пустая (Shikimori не ответил) — число просто не подставляется.
 */
export function buildGenreDescription(genre: GenreLanding, count?: number): string {
  const withCount = count && count > 0 ? `${count} аниме в жанре` : `Аниме в жанре`
  return (
    `${genre.hint}. Смотрите ${withCount} «${genre.name}» онлайн бесплатно в хорошем ` +
    `качестве HD с русской озвучкой и субтитрами. Новые серии появляются на Weebx каждый день.`
  )
}