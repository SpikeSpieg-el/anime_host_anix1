export interface GenreLanding {
  /** Сегмент маршрута: /genre/isekai */
  slug: string
  /** Русское название жанра — по нему фильтруется каталог и Shikimori API */
  name: string
  /** ID жанра в Shikimori (строка, как в GENRES_MAP) */
  genreId: string
  /** Короткое описание жанра. Идёт в meta description и в видимый текст страницы. */
  hint: string
  /**
   * Цвет акцента для точки на плашке (детерминированно по индексу жанра).
   * Заменяет эмодзи: в разметку попадает один span с background-color и
   * ничего больше.
   */
  accent: string
  /**
   * false для 18+ жанров: роут остаётся рабочим, но страница отдаёт noindex
   * и не попадает ни в sitemap, ни в хаб /genre.
   */
  indexable: boolean
}

