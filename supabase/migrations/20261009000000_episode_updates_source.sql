-- ============================================================================
-- РАЗДЕЛЕНИЕ ИСТОЧНИКОВ УВЕДОМЛЕНИЙ (episode_updates.source)
-- ============================================================================
--
-- ЧТО БЫЛО НЕ ТАК
--   В `episode_updates` писали ДВА независимых механизма, и оба считали
--   колокольчик своим:
--
--     1. Браузер (`EpisodeUpdatesProvider.checkAnimeUpdates`) — по Shikimori:
--        «у онгоинга вышла 3-я серия». Значение `new_episode` здесь — это
--        `episodes_aired`.
--     2. Сервер (`POST /api/alerts/check` и телеграм-бот) — по Kodik:
--        «появилась озвучка», и `new_episode` там — сколько серий реально
--        доступно В МАТЕРИАЛЕ, а не сколько вышло в оригинале.
--
--   Колонки это различали никак, поэтому механизмы затирали друг друга. Для
--   тайтла, у которого озвучка появилась (Kodik: 12 серий), но по оригиналу
--   вышло 3 (Shikimori), браузер перезаписывал `new_episode` на 3 — и человек
--   видел «3» вместо «12», то есть ровно то, о чём его и просили уведомить.
--
--   Защита была костылём: `protectedIds` в провайдере держал тайтлы из
--   `translation_alerts` и запрещал их УДАЛЯТЬ — но не запрещал ПЕРЕЗАПИСЫВАТЬ.
--   Ровно та ветка кода, где нужна была защита, её и не имела.
--
-- ЧТО СТАЛО
--   `source` отвечает на вопрос «кто это записал», и браузер больше не
--   трогает записи, которые записал не он. Это убирает и затирание, и костыль
--   `protectedIds` для этой задачи: правило «своё не трогаю, чужое не
--   удаляю» выражается прямо и не требует окна в 30 дней.
--
-- ЗНАЧЕНИЯ
--   'shikimori' — новая серия по episodes_aired (браузер);
--   'dub'       — появилась озвучка/серия в Kodik (сервер: /api/alerts/check
--                 и телеграм-бот).
--
-- ПОРЯДОК ПРИМЕНЕНИЯ: миграция до деплоя приложения.
-- ============================================================================

-- Строки, созданные до миграции, источника не имеют. Для них выбираем
-- источник по совпадению с закрытым ожиданием озвучки: если по этому тайтлу
-- у пользователя было ожидание и оно сработало, запись почти наверняка от
-- сервера. Всё остальное — от браузера.
ALTER TABLE public.episode_updates
  ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'shikimori';

-- CHECK добавляем отдельным DO-блоком: если колонка уже была (повторное
-- применение миграции) с другим набором значений, ALTER с ограничением
-- упал бы, а DO-блок спокойно проверит текущее состояние.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'episode_updates_source_check'
  ) THEN
    ALTER TABLE public.episode_updates
      ADD CONSTRAINT episode_updates_source_check
      CHECK (source IN ('shikimori', 'dub'));
  END IF;
END;
$$;

-- Проставляем источник существующим строкам. Только те, у которых есть
-- закрытое ожидание озвучки по тому же тайтлу.
UPDATE public.episode_updates eu
SET source = 'dub'
WHERE eu.source = 'shikimori'
  AND EXISTS (
    SELECT 1
    FROM public.translation_alerts ta
    WHERE ta.user_id = eu.user_id
      AND ta.anime_id = eu.anime_id
      AND ta.notified_at IS NOT NULL
  );

-- Клинер читает список уведомлений и перезаписывает строки пачкой; ему
-- нужно отличать свои от чужих. Частичный индекс по 'dub' отвечает на
-- вопрос «какие записи мне нельзя трогать» за один проход индекса.
CREATE INDEX IF NOT EXISTS episode_updates_source_idx
  ON public.episode_updates (user_id, source);

COMMENT ON COLUMN public.episode_updates.source IS
  'Кто записал: shikimori — новая серия по episodes_aired (браузер); dub — появилась озвучка в Kodik (сервер/бот). Браузер не перезаписывает чужие записи';