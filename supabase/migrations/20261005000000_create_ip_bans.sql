-- ============================================================================
-- ЧЁРНЫЙ СПИСОК IP (ip_bans)
-- ============================================================================
--
-- ЗАЧЕМ
--   Антипиратские сканеры (F6 и подобные) ходят по страницам /watch/...
--   с серверных IP (хостинг-провайдеры уровня Selectel, Hetzner, VDSina).
--   Пока плеер спрятан за шифрованными ссылками /embed/<токен>, это второй
--   рубеж: такие адреса банятся целиком, при желании — всей подсетью.
--
-- КАК ИСПОЛЬЗУЕТСЯ
--   Записи добавляются из админ-панели (вкладка «Чёрный список»): одиночный
--   IP или CIDR-подсеть. Middleware сверяет адрес посетителя со списком
--   (кэш в памяти ~30 секунд) и отдаёт забаненным обычный 404 — без
--   намёка, что это блокировка.
--
--   Дополнительно есть аварийный список в env BLOCKED_IPS (через запятую) —
--   применяется мгновенно, без перезаписи в базу.
--
-- ПОРЯДОК ПРИМЕНЕНИЯ: миграция до деплоя приложения.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.ip_bans (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Одиночный IP (5.128.0.1) или подсеть (5.128.0.0/24, 2a03:d000::/48).
  -- Хранится в каноническом виде — приложение нормализует перед записью.
  target TEXT NOT NULL UNIQUE CHECK (char_length(target) BETWEEN 7 AND 49),
  -- Человекочитаемая причина: «ночной сканер /watch/61607», «Hetzner ASN...»
  reason TEXT,
  -- Откуда запись: 'admin' | 'env' | ...
  source TEXT NOT NULL DEFAULT 'admin',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ip_bans_created_at_idx
  ON public.ip_bans (created_at DESC);

-- Список читает только бэкенд (service role). Для остальных — пусто:
-- включаем RLS без единой политики.
ALTER TABLE public.ip_bans ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.ip_bans IS
  'Чёрный список IP/CIDR: middleware отдаёт этим адресам 404.';
