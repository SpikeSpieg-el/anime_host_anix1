/**
 * Генератор секрета captcha.
 *
 * Печатает новый секрет в stdout. Копировать его нужно в переменную окружения
 * сервиса (Coolify -> Service -> Environment variables -> CAPTCHA_SECRET),
 * а не в код и не в git.
 *
 *     npm run captcha:secret
 *
 * Секрет обязателен: без него lib/captcha-secret.ts бросает исключение, и
 * капча не работает вовсе. Это намеренно лучше, чем молчаливая подстановка
 * значения из репозитория.
 */

import crypto from "node:crypto"

const secret = crypto.randomBytes(32).toString("hex")

process.stdout.write(
  [
    "",
    "Новый CAPTCHA_SECRET:",
    "",
    `  ${secret}`,
    "",
    "Что сделать:",
    "  1. Прописать значение в переменную CAPTCHA_SECRET окружения (Coolify).",
    "  2. Перезапустить сервис.",
    "",
    "Внимание: старый секрет скомпрометирован, если репозиторий когда-либо был",
    "публичным. Ротация обязательна даже вместе с удалением литерала из кода.",
    "",
  ].join("\n"),
)